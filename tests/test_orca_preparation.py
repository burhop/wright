def test_inspection_reads_actual_package_and_preserves_three_artifact_identities(
    inspection,
):
    root, config, raw = inspection
    operation.inspect(config, vars(three_mf_geometry), read_3mf_toolpaths)
    evidence = json.loads((root / "out/slice-evidence.json").read_bytes())
    assert evidence["operation"] == "actual_local_orca_slice"
    assert (
        evidence["simulation"] is False and evidence["engineering_acceptance"] is False
    )
    for key, name in [
        ("source_sha256", "repaired.stl"),
        ("prepared_sha256", "out/prepared-model.3mf"),
        ("package_sha256", "out/slice_package.gcode.3mf"),
    ]:
        assert evidence[key] == operation.sha((root / name).read_bytes())
    summary = json.loads((root / "out/toolpath-summary.json").read_bytes())
    assert summary["layer_count"] == 50
    assert summary["provenance"]["selected_section"]["start_marker"] == ";VT0"
    assert "custom" in summary["provenance"]["unclassified_features"]
    assert evidence["geometry"]["inverse_model_error_mm"] < 1e-12
    assert (root / "repaired.stl").read_bytes() == raw


@pytest.mark.parametrize(
    "fault",
    [
        "response_error",
        "native_failure",
        "native_bool",
        "effective_settings",
        "profile",
        "prepared",
        "source",
    ],
)
def test_independent_inspection_rejects_unsupported_or_changed_evidence(
    inspection, fault
):
    root, config, _ = inspection
    if fault == "response_error":
        (root / "out/slice-provider-response.json").write_text(
            json.dumps({"content": [], "isError": True})
        )
    elif fault.startswith("native"):
        (root / "out/result.json").write_text(
            json.dumps({"return_code": False if fault == "native_bool" else 139})
        )
    elif fault == "effective_settings":
        (root / "out/effective-settings.json").write_text(
            json.dumps({"wall_loops": "4"})
        )
    elif fault == "profile":
        (root / "process.json").write_bytes(b'{"changed":true}')
    elif fault == "prepared":
        (root / "out/prepared-model.3mf").write_bytes(b"not a zip")
    else:
        raw = bytearray((root / "repaired.stl").read_bytes())
        raw[96:100] = struct.pack("<f", 99)
        (root / "repaired.stl").write_bytes(raw)
    with pytest.raises((ValueError, KeyError, __import__("zipfile").BadZipFile)):
        operation.inspect(config, vars(three_mf_geometry), read_3mf_toolpaths)
    assert not (root / "out/slice-evidence.json").exists()
