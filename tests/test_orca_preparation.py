def test_standard_preparation_keeps_original_model_and_records_explicit_build_frame(
    inputs,
):
    root, config, raw = inputs
    evidence = operation.prepare(config, vars(three_mf_geometry))
    assert (root / "repaired.stl").read_bytes() == raw
    prepared = (root / "out/prepared-model.3mf").read_bytes()
    world, records = three_mf_geometry.read_package(prepared)
    assert records[0]["model_triangles"] == three_mf_geometry.stl_triangles(raw)
    assert evidence["source_sha256"] == operation.sha(raw)
    assert evidence["prepared_sha256"] == operation.sha(prepared)
    assert evidence["geometry"]["prepared_model_error_mm"] == 0
    assert three_mf_geometry.bounds(world) == [[123, 125.5, 0], [133, 130.5, 10]]
    assert (
        b'name="object"'
        in three_mf_geometry.archive_members(prepared)["3D/3dmodel.model"]
    )
    with pytest.raises(FileExistsError):
        operation.prepare(config, vars(three_mf_geometry))


