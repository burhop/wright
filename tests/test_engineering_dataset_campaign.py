def test_dashboard_binds_before_slow_background_reconciliation(monkeypatch, tmp_path):
    scan_started = threading.Event()
    release_scan = threading.Event()
    served = threading.Event()

    class SlowCampaign:
        root = tmp_path

        def scan(self):
            scan_started.set()
            release_scan.wait(2)

        def reconciliation_failed(self, error):  # pragma: no cover - defensive path
            raise AssertionError(error)

    class FakeServer:
        def __init__(self, address, handler):
            self.address = address

        def serve_forever(self):
            assert scan_started.wait(1)
            served.set()
            release_scan.set()

        def server_close(self):
            pass

    monkeypatch.setattr(campaign_module, "ThreadingHTTPServer", FakeServer)
    campaign_module.serve(SlowCampaign(), 18771)
    assert served.is_set()


def test_same_attempt_cannot_erase_a_previously_observed_run_milestone(corpus):
    path, receipt, _ = make_receipt(corpus)
    corpus.scan()
    receipt.update(accepted_by_runtime=False, status="preflight_rejected",
                   terminal_step_reached=False, all_required_steps_succeeded=False)
    write_json(path, receipt)
    corpus.scan()
    metrics = corpus.status()["metrics"]
    assert metrics["combinations_run"] == metrics["processes_with_outputs"] == 1
    for metric in ("combinations_run", "processes_with_outputs"):
        values = [h["metrics"][metric] for h in corpus.status()["history"]]
        assert values == sorted(values)


def test_revision_change_keeps_history_but_does_not_verify_new_inputs(corpus):
    _, _, dataset = make_receipt(corpus)
    corpus.scan()
    prior = current_case(corpus)
    prompt = corpus.inputs / "scenarios" / dataset["path"] / "prompt.txt"
    prompt.write_text("A materially changed requested geometry.", encoding="utf-8")
    corpus.scan()
    current = current_case(corpus)
    assert current["digest"] != prior["digest"]
    assert current["completed_current_revision"] is False
    assert current["latest_status"] == "not_run"
    assert corpus.status()["metrics"]["processes_with_outputs"] == 1


