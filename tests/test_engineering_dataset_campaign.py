@pytest.mark.parametrize("relative", ["../outside.txt", "/outside.txt", "..\\outside.txt"])
def test_shared_input_and_output_file_boundary_rejects_escape(tmp_path, relative):
    root = tmp_path / "allowed"
    root.mkdir()
    (tmp_path / "outside.txt").write_text("outside", encoding="utf-8")
    with pytest.raises(ValueError):
        safe_file(root, relative)


def test_absolute_path_and_symlink_escape_are_rejected(tmp_path):
    root = tmp_path / "allowed"
    root.mkdir()
    outside = tmp_path / "outside.txt"
    outside.write_text("outside", encoding="utf-8")
    with pytest.raises(ValueError):
        safe_file(root, outside.as_posix())
    try:
        (root / "link.txt").symlink_to(outside)
    except (OSError, NotImplementedError):
        return  # Windows hosts may lack the OS privilege for a symlink fixture.
    with pytest.raises(ValueError):
        safe_file(root, "link.txt")


