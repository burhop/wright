@pytest.mark.parametrize("defect", ["missing", "empty", "digest_mismatch", "input_copy"])
def test_required_files_must_exist_be_nonempty_and_match_generated_identity(corpus, defect):
    path, receipt, dataset = make_receipt(corpus)
    entry = receipt["produced_files"][0]
    output = path.parent / "artifacts" / entry["path"]
    if defect == "missing":
        output.unlink()
    elif defect == "empty":
        output.write_bytes(b"")
        entry["sha256"] = digest(b"")
    elif defect == "digest_mismatch":
        output.write_bytes(b"changed after the adapter recorded it")
    else:
        prompt = corpus.inputs / "scenarios" / dataset["path"] / "prompt.txt"
        output.write_bytes(prompt.read_bytes())
        entry["sha256"] = digest(prompt.read_bytes())
    write_json(path, receipt)
    corpus.scan()
    case = current_case(corpus)
    check = case["latest_attempt"]["output_check"]
    assert check["passed"] is False
    assert "mesh" in check["missing_roles"]
    assert check["errors"]
    assert corpus.status()["metrics"]["processes_with_outputs"] == 0


def test_prose_or_manifest_without_required_outputs_does_not_pass(corpus):
    path, receipt, dataset = make_receipt(corpus)
    receipt["produced_files"] = [{"artifact_id": "prose", "path": "answer.md",
                                  "sha256": digest(b"The model is ready.")}]
    (path.parent / "artifacts" / "answer.md").write_bytes(b"The model is ready.")
    check = check_outputs(dataset, receipt, path.parent / "artifacts")
    assert check["passed"] is False
    assert set(check["missing_roles"]) == {"mesh", "report"}


def test_unchanged_receipt_reaudits_artifact_integrity_without_erasing_history(corpus):
    path, receipt, _ = make_receipt(corpus)
    corpus.scan()
    assert current_case(corpus)["completed_current_revision"] is True, corpus.status()["issues"]
    (path.parent / "artifacts" / receipt["produced_files"][0]["path"]).unlink()
    corpus.scan()
    case = current_case(corpus)
    assert case["completed_current_revision"] is False
    assert case["latest_attempt"]["output_check"]["passed"] is False
    # Cumulative milestones describe the event when a full output set existed.
    # The current integrity projection must remain separate from that history.
    assert corpus.status()["metrics"]["processes_with_outputs"] == 1


def test_incremental_scan_reuses_hashes_until_output_metadata_changes(corpus, monkeypatch):
    path, receipt, _ = make_receipt(corpus)
    corpus.scan()
    original = __import__(
        "scripts.engineering_dataset_campaign", fromlist=["check_outputs"]
    ).check_outputs
    calls = []

    def observed(*args, **kwargs):
        calls.append(args[2])
        return original(*args, **kwargs)

    monkeypatch.setattr(
        "scripts.engineering_dataset_campaign.check_outputs", observed
    )
    corpus.scan()
    assert calls == []
    output = path.parent / "artifacts" / receipt["produced_files"][0]["path"]
    output.write_bytes(b"changed output bytes")
    corpus.scan()
    assert calls == [path.parent / "artifacts"]
    assert current_case(corpus)["latest_attempt"]["output_check"]["passed"] is False


