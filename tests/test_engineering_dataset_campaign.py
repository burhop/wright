def make_receipt(campaign, scenario="sample-process-01", attempt="attempt-001", **overrides):
    campaign.scan()
    dataset = next(d for d in campaign.status()["datasets"] if d["scenario_id"] == scenario)
    directory = campaign.root / "output" / scenario / attempt
    artifacts = directory / "artifacts"
    artifacts.mkdir(parents=True, exist_ok=True)
    # Deliberately not real engineering outputs: this test verifies file presence,
    # not STL/JSON correctness. It proves that content validity stays at zero.
    outputs = {"generated-part.stl": b"pytest generated bytes, not a qualified mesh",
               "results/report.json": b'{"pytest_only": true}'}
    files = []
    for name, content in outputs.items():
        path = artifacts / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        files.append({"artifact_id": "test-artifact-" + str(len(files)),
                      "path": name, "sha256": digest(content)})
    receipt = {
        "scenario_id": scenario,
        "attempt_id": attempt,
        "dataset_digest": dataset["digest"],
        "template_digest": dataset["template_digest"],
        "definition_digest": "a" * 64,
        "accepted_by_runtime": True,
        "run_id": "pytest-only-" + attempt,
        "execution_kind": "integration",
        "status": "completed",
        "started_at": "2026-09-12T10:00:00Z",
        "finished_at": "2026-09-12T10:01:00Z",
        "terminal_step_reached": True,
        "all_required_steps_succeeded": True,
        "external_effects": "test_destinations",
        "produced_files": files,
    }
    receipt.update(overrides)
    path = directory / "run.json"
    write_json(path, receipt)
    return path, receipt, dataset


def current_case(campaign, scenario="sample-process-01"):
    return next(d for d in campaign.status()["datasets"] if d["scenario_id"] == scenario)


def test_zero_origin_registration_scan_and_restart_are_idempotent(corpus):
    origin = corpus.status()
    assert origin["metrics"] == {
        "datasets_created": 0, "combinations_run": 0,
        "processes_with_outputs": 0, "valid_data": 0,
    }
    corpus.scan()
    first = corpus.status()
    assert first["metrics"]["datasets_created"] == 3
    assert first["history"][0]["metrics"] == origin["metrics"]
    assert [h["metrics"]["datasets_created"] for h in first["history"]] == [0, 1, 2, 3]
    corpus.scan()
    second = corpus.status()
    assert {k: v for k, v in second.items() if k != "reconciliation"} == {
        k: v for k, v in first.items() if k != "reconciliation"
    }
    restarted = Campaign(corpus.inputs, corpus.root, corpus.templates)
    restarted.scan()
    assert {
        k: v for k, v in restarted.status().items() if k != "reconciliation"
    } == {k: v for k, v in first.items() if k != "reconciliation"}
    assert list((corpus.root / "output").glob("*/*")) == []


def test_retry_attempts_and_restart_count_a_pair_only_once(corpus):
    make_receipt(corpus, status="failed", terminal_step_reached=False,
                 all_required_steps_succeeded=False)
    corpus.scan()
    assert corpus.status()["metrics"]["combinations_run"] == 1
    assert corpus.status()["metrics"]["processes_with_outputs"] == 0
    make_receipt(corpus, attempt="attempt-002")
    corpus.scan()
    assert corpus.status()["metrics"] == {
        "datasets_created": 3, "combinations_run": 1,
        "processes_with_outputs": 1, "valid_data": 0,
    }
    assert current_case(corpus)["attempts"] == 2
    before = corpus.status()
    Campaign(corpus.inputs, corpus.root, corpus.templates).scan()
    assert corpus.status() == before
    make_receipt(corpus, scenario="sample-process-02")
    corpus.scan()
    assert corpus.status()["metrics"]["combinations_run"] == 2
    assert corpus.status()["metrics"]["processes_with_outputs"] == 2


