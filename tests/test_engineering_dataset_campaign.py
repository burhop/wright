def attach_full_scope_assessment(corpus, path, receipt, *, profile_id="qualified-profile",
                                 subject_sha=None, text="Requirement café"):
    profile_ref = {"id": profile_id, "version": "1", "sha256": "1" * 64}
    baseline_ref = {"id": "qualified-baseline", "version": "1", "sha256": "2" * 64}
    subject_sha = subject_sha or receipt["produced_files"][0]["sha256"]
