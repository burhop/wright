def test_dashboard_binds_before_slow_background_reconciliation(monkeypatch, tmp_path):
    scan_started = threading.Event()
    release_scan = threading.Event()
    served = threading.Event()

    class SlowCampaign:
        root = tmp_path

        def scan(self):
            scan_started.set()
            release_scan.wait(2)

        def reconciliation_failed(self, error):  # pragma: no cover - defensive path
            raise AssertionError(error)

    class FakeServer:
        def __init__(self, address, handler):
            self.address = address

        def serve_forever(self):
            assert scan_started.wait(1)
            served.set()
            release_scan.set()

        def server_close(self):
            pass

    monkeypatch.setattr(campaign_module, "ThreadingHTTPServer", FakeServer)
    campaign_module.serve(SlowCampaign(), 18771)
    assert served.is_set()


