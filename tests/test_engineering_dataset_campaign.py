def test_approval_modes_are_validated_persisted_and_idempotent(corpus):
    assert corpus.status()["approval_mode"] == "manual"
    corpus.configure("auto")
    automatic = corpus.status()
    assert automatic["approval_mode"] == "auto"
    corpus.configure("auto")
    assert corpus.status() == automatic
    assert Campaign(corpus.inputs, corpus.root, corpus.templates).status()["approval_mode"] == "auto"
    corpus.configure("manual")
    with pytest.raises(ValueError, match="manual or auto"):
        corpus.configure("approve_everything")
    assert corpus.status()["approval_mode"] == "manual"
