def make_receipt(campaign, scenario="sample-process-01", attempt="attempt-001", **overrides):
    campaign.scan()
    dataset = next(d for d in campaign.status()["datasets"] if d["scenario_id"] == scenario)
    directory = campaign.root / "output" / scenario / attempt
    artifacts = directory / "artifacts"
    artifacts.mkdir(parents=True, exist_ok=True)
    # Deliberately not real engineering outputs: this test verifies file presence,
    # not STL/JSON correctness. It proves that content validity stays at zero.
    outputs = {"generated-part.stl": b"pytest generated bytes, not a qualified mesh",
               "results/report.json": b'{"pytest_only": true}'}
    run_id = "pytest-only-" + attempt
    files = []
    for name, content in outputs.items():
        path = artifacts / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
        output_port = "mesh" if name.endswith(".stl") else "report"
        files.append({"artifact_id": "test-artifact-" + str(len(files)),
                      "path": name, "sha256": digest(content), "run_id": run_id,
                      "task_id": "produce", "output_port": output_port,
                      "artifact_role": "deliverable"})
    receipt = {
        "scenario_id": scenario,
        "attempt_id": attempt,
        "dataset_digest": dataset["digest"],
        "template_digest": dataset["template_digest"],
        "definition_digest": "a" * 64,
        "accepted_by_runtime": True,
        "run_id": run_id,
        "execution_kind": "integration",
        "status": "completed",
        "started_at": "2026-09-12T10:00:00Z",
        "finished_at": "2026-09-12T10:01:00Z",
        "terminal_step_reached": True,
        "all_required_steps_succeeded": True,
        "external_effects": "test_destinations",
        "produced_files": files,
    }
    receipt.update(overrides)
    path = directory / "run.json"
    write_json(path, receipt)
    return path, receipt, dataset


