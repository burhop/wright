"""Author two exact standard-3MF/Orca handoffs on the existing source runtime."""

from copy import copy
import json
from pathlib import Path


def add(parent, definition, binding_module, binding, bindings, repair, profiles):
    selected = binding["selected_orientation"]
    other = "side" if selected == "pads_down" else "pads_down"
    asset_paths = {
        "geometry": definition.resource("packages/workspace_service/src/workspace_service/process_validation/readers/three_mf_geometry.py"),
        "paths": definition.resource("packages/workspace_service/src/workspace_service/process_interfaces/representations.py"),
        "operation": Path(__file__).with_name("orca-preparation.py"),
    }
    assets = {
        name: (
            parent.input_bytes(
                "orca-" + name + ".py",
                path.read_bytes(),
                kind="workspace_file",
                original=str(path),
            ),
            parent.input_root + "/orca-" + name + ".py",
            definition.sha(path.read_bytes()),
        )
        for name, path in asset_paths.items()
    }
    mount = bindings["inspection_workspace"].rstrip("/")
    source_ref = repair["id"] + ".repaired_mesh"
    source_path = parent.output + "/repaired_mesh.stl"
    profile_deps = {
        role: (ref, parent.input_root + "/" + role + "-profile.json")
        for role, ref in profiles.items()
    }

    def python_stage(
        flow, identity, title, function, config, outputs, dependencies, *, readers
    ):
        step = flow.stage(identity, title)
        code = "import hashlib\nfrom pathlib import Path\n"
        for name in readers:
            ref, path, digest = assets[name]
            code += f"raw=Path({(mount + '/' + path)!r}).read_bytes()\nassert hashlib.sha256(raw).hexdigest()=={digest!r}\n{name}={{'__name__':'accepted_operation'}}\nexec(compile(raw,{path!r},'exec'),{name})\n"
            dependencies["asset_" + name] = (ref, path)
        arguments = {
            "prepare": ",geometry",
            "inspect": ",geometry,paths['read_3mf_toolpaths']",
            "compare": "",
        }[function]
        code += f"print(operation[{function!r}]({config!r}{arguments}))\n"
        call = flow.input_bytes(
            identity + "-call.json",
            (
                json.dumps(
                    dict(
                        solver=bindings["inspection_backend"],
                        input_content=code,
                        job_name=flow.output + "/" + identity,
                        critic_approved=False,
                    ),
                    indent=2,
                )
                + "\n"
            ).encode(),
            run_paths=True,
        )
        port = flow.reference(call, step, "exact_arguments")
        flow.exact_mcp(
            step,
            flow.select(bindings["inspection_server"], "run_simulation"),
            port,
            tuple(outputs.values()),
            identity + "-provider-response.json",
        )
        step["fields"]["settings"]["mcp_file_dependencies"] = {
            flow.reference(ref, step, key, "workspace_file"): path
            for key, (ref, path) in dependencies.items()
        }
        flow.file_outputs(
            step, {role: flow.output + "/" + name for role, name in outputs.items()}
        )
        return step

    cases, chain = {}, []
    for name in (selected, other):
        flow = copy(parent)
        auxiliary = name != selected
        if auxiliary:
            flow.suffix += "_comparison"
            flow.output += "/comparison"
            flow.input_root += "/comparison"
        prefix = "comparison_" if auxiliary else ""
        config = dict(
            workspace_root=mount,
            source_mesh=source_path,
            output_root=flow.output,
            orientation=name,
            rotation=binding_module.ROTATIONS[name],
            build_center_xy_mm=binding_module.CENTER,
            profiles={role: path for role, (_, path) in profile_deps.items()},
            profile_sha256={
                role: bindings["profiles"][role]["sha256"] for role in profiles
            },
            effective_settings=binding_module.EFFECTIVE,
            engine_header="; generated by OrcaSlicer 2.4.2 on ",
            nominal_layer_section={
                "start_marker": ";VT0",
                "end_marker": "; filament end gcode",
            },
        )
        prepare = python_stage(
            flow,
            "prepare_build_instance",
            "Prepare " + name.replace("_", " ") + " from unchanged model geometry",
            "prepare",
            config,
            {
                prefix + "prepared_3mf": "prepared-model.3mf",
                prefix + "preparation_evidence": "preparation-evidence.json",
            },
            {"source_mesh": (source_ref, source_path)},
            readers=("geometry", "operation"),
        )
        slicer = (
            flow.stage("slice_candidate", "Slice the comparison orientation")
            if auxiliary
            else parent.original("supports_and_slice")
        )
        call = flow.input_bytes(
            "orca-slice-call.json",
            (
                json.dumps(
                    binding_module.arguments(
                        parent,
                        binding,
                        flow.output + "/prepared-model.3mf",
                        flow.output,
                    ),
                    indent=2,
                )
                + "\n"
            ).encode(),
            run_paths=True,
        )
        port = flow.reference(call, slicer, "exact_arguments")
        flow.exact_mcp(
            slicer,
            flow.select(bindings["slicer_server"], "shell_execute"),
            port,
            ("slice_package.gcode.3mf", "result.json", "effective-settings.json"),
            "slice-provider-response.json",
        )
        slicer["fields"]["settings"]["timeout_seconds"] = 60
        deps = {
            **profile_deps,
            "original_repaired_mesh": (source_ref, source_path),
            "prepared_build_instance": (
                prepare["id"] + "." + prefix + "prepared_3mf",
                flow.output + "/prepared-model.3mf",
            ),
        }
        slicer["fields"]["settings"]["mcp_file_dependencies"] = {
            flow.reference(ref, slicer, key, "workspace_file"): path
            for key, (ref, path) in deps.items()
        }
        slice_roles = flow.file_outputs(
            slicer,
            {
                prefix + role: flow.output + "/" + filename
                for role, filename in {
                    "slice_package": "slice_package.gcode.3mf",
                    "native_result": "result.json",
                    "effective_settings": "effective-settings.json",
                }.items()
            },
        )
        response_port = prefix + "provider_response"
        slicer["fields"]["outputs"].append(
            definition.port(response_port, "workspace_file")
        )
        slicer["fields"]["settings"].update(
            saved_response_file_port=response_port,
            file_policy="publish_overwrite",
        )
        deps.update(
            {
                "provider_response": (
                    slicer["id"] + "." + response_port,
                    flow.output + "/slice-provider-response.json",
                )
            }
        )
        for role, (producer, key, _) in slice_roles.items():
            deps[role] = (
                producer["id"] + "." + key,
                producer["fields"]["settings"]["expected_file_ports"][key],
            )
        inspected = python_stage(
            flow,
            "inspect_slice_handoff",
            "Inspect actual geometry, settings and nominal paths",
            "inspect",
            config,
            {
                prefix + "slice_evidence": "slice-evidence.json",
                prefix + "support_preview": "support-preview.json",
                prefix + "toolpath_summary": "toolpath-summary.json",
                **{
                    prefix + role + "_profile": role + "-profile.json"
                    for role in profiles
                },
            },
            deps,
            readers=("geometry", "paths", "operation"),
        )
        chain.extend([prepare, slicer, inspected])
        cases[name] = dict(
            flow=flow,
            prepare=prepare,
            slice=slicer,
            inspect=inspected,
            prefix=prefix,
            slice_roles=slice_roles,
        )
    primary, auxiliary = cases[selected], cases[other]
    deps = {"source_mesh": (source_ref, source_path)}
    for name, case in cases.items():
        for step in (case["prepare"], case["slice"], case["inspect"]):
            settings = step["fields"]["settings"]
            files = dict(settings["expected_file_ports"])
            if settings.get("saved_response_file_port"):
                files[settings["saved_response_file_port"]] = settings[
                    "output_filename"
                ]
            for role, path in files.items():
                deps[name + "_" + role] = (step["id"] + "." + role, path)
    compare = python_stage(
        parent,
        "compare_orientations",
        "Compare exact pads-down and side evidence",
        "compare",
        dict(
            workspace_root=mount,
            output_root=parent.output,
            source_mesh=source_path,
            selected_orientation=selected,
            cases={name: case["flow"].output for name, case in cases.items()},
        ),
        {"orientation_comparison": "orientation-comparison.json"},
        deps,
        readers=("operation",),
    )
    chain.append(compare)
    inspect_roles = {
        role: (primary["inspect"], role, "workspace_file")
        for role in primary["inspect"]["fields"]["settings"]["expected_file_ports"]
        if role != "toolpath_summary"
    }
    extra_sources = {
        role: source
        for case in cases.values()
        for role, source in case["slice_roles"].items()
        if role != "slice_package"
    }
    for case in cases.values():
        key = case["prefix"] + "prepared_3mf"
        extra_sources[key] = (case["prepare"], key, "workspace_file")
    review_refs = [
        (
            compare["id"] + ".orientation_comparison",
            "orientation_comparison",
            "workspace_file",
        )
    ]
    for name, case in cases.items():
        for step in (case["prepare"], case["slice"], case["inspect"]):
            settings = step["fields"]["settings"]
            keys = list(settings["expected_file_ports"])
            if settings.get("saved_response_file_port"):
                keys.append(settings["saved_response_file_port"])
            for key in keys:
                review_refs.append(
                    (step["id"] + "." + key, name + "_" + key, "workspace_file")
                )
    return dict(
        chain=chain,
        slice_step=primary["slice"],
        inspect_step=primary["inspect"],
        comparison_reference=compare["id"] + ".orientation_comparison",
        slice_roles={"slice_package": primary["slice_roles"]["slice_package"]},
        inspect_roles=inspect_roles,
        extra_sources=extra_sources,
        review_refs=review_refs,
    )
